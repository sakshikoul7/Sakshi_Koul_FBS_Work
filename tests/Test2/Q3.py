#to calculate the total cost of fencing the field where the field is half in circle share and rest rectangular share. The cost of fencing the 35Rs per meter. The radius of circular share is 20m and length is 50m and breadth of rectangular share is 40m.

radius = 20
length = 50
breadth = 40
pi = 3.14
circular_share = pi * radius
rectangular_share = 2 * (length + breadth)
total_fencing = circular_share + rectangular_share
cost_per_meter = 35
total_cost = total_fencing * cost_per_meter
print("Total cost of fencing the field is:", total_cost)

